"""Generate docs/planning/benchmark-history.md from
tools/benchmarks/benchmark_history.jsonl.

Same shape as every other generator in this file: a data source
(`benchmark_history.jsonl`, appended to by `tools/benchmarks/
benchmark_demos.py --record`, never hand-edited) and a rendered,
human-readable view of it (`docs/planning/benchmark-history.md`, also
never hand-edited). `make benchmark-report` writes it; `make
check-benchmark-report` (part of `make ci`) fails if the committed copy
is stale relative to the JSONL.

**The one thing this generator cannot fix, unlike every sibling in this
file**: whether a new benchmark config gets added to
`tools/benchmarks/benchmark_demos.py`'s own `DEFAULT_CONFIGS` when new
functionality earns one, and whether `make record-benchmarks` actually
gets run at a version bump. Both are practices
(`tools/benchmarks/CLAUDE.md`'s own standing rule), not structural
facts -- there is nothing here to check that a benchmark *should* exist
for something, only that the ones that do exist are rendered accurately.

**Numbers across rows are only comparable when `hostname` matches.**
This generator does not attempt to normalise across machines -- it
renders `hostname` on every row instead, so a reader comparing two rows
can see when that comparison isn't a fair one.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[2]
HISTORY_PATH = REPO_ROOT / "tools" / "benchmarks" / "benchmark_history.jsonl"
OUTPUT_PATH = REPO_ROOT / "docs" / "planning" / "benchmark-history.md"


def load_records(history_path: Path = HISTORY_PATH) -> list[dict[str, Any]]:
    """Every recorded run, in file order -- empty if the history doesn't
    exist yet (a real, honest state: nothing has been recorded), not an
    error.
    """
    if not history_path.exists():
        return []
    records = []
    with history_path.open("r", encoding="utf-8") as handle:
        for line in handle:
            stripped = line.strip()
            if stripped:
                records.append(json.loads(stripped))
    return records


def render(records: list[dict[str, Any]]) -> str:
    lines = [
        "# Benchmark History",
        "",
        # Emitted here, not hand-written, the same reasoning
        # generate_dependency_tree.py's own render() gives: a declaration
        # added by hand would be erased by the next run.
        "Checked-by: generated (make benchmark-report)",
        "",
        "**Generated by `tools/generators/generate_benchmark_report.py`",
        "from `tools/benchmarks/benchmark_history.jsonl`. Do not edit by",
        "hand** -- per root `CLAUDE.md`, generated documentation is never",
        "edited manually, and `make check-benchmark-report` fails if this",
        "file and the history disagree. Add an entry by running",
        "`make record-benchmarks`, never by editing this file or the",
        "JSONL directly.",
        "",
        "Every row is one real `pyflow run` subprocess measurement, split",
        "into startup (one frame, includes any one-time cost such as",
        "`PISO`'s cached Poisson-matrix build) and steady per-frame cost",
        "-- see `tools/benchmarks/CLAUDE.md`'s own `--phases`/`--record`",
        "entries for the full mechanism. **Only compare rows with the",
        "same `hostname`** -- run-to-run noise within one machine and a",
        "genuine difference between two machines are not the same thing,",
        "and this history does not try to tell them apart.",
        "",
    ]

    if not records:
        lines += [
            "No benchmark records yet. Run `make record-benchmarks` to add",
            "the first one.",
            "",
        ]
        return "\n".join(lines)

    by_config: dict[str, list[dict[str, Any]]] = {}
    for record in records:
        by_config.setdefault(record["config"], []).append(record)

    for config in sorted(by_config):
        entries = sorted(by_config[config], key=lambda r: r["timestamp"], reverse=True)
        lines.append(f"## `{config}`")
        lines.append("")
        lines.append(
            "| timestamp | version | commit | hostname | frames | repeats "
            "| startup min (s) | per-frame min (s) | total min (s) |"
        )
        lines.append("|---|---|---|---|---|---|---|---|---|")
        for entry in entries:
            lines.append(
                f"| {entry['timestamp']} | {entry['pyflow_version']} "
                f"| {entry['git_commit']} | {entry['hostname']} "
                f"| {entry['frames']} | {entry['repeats']} "
                f"| {entry['startup_min_s']:.3f} | {entry['per_frame_min_s']:.4f} "
                f"| {entry['total_min_s']:.3f} |"
            )
        lines.append("")

    return "\n".join(lines)


def main() -> int:
    content = render(load_records())
    check_only = "--check" in sys.argv[1:]

    if check_only:
        current = OUTPUT_PATH.read_text(encoding="utf-8") if OUTPUT_PATH.exists() else None
        if current == content:
            print("docs/planning/benchmark-history.md is up to date.")
            return 0
        print(
            "docs/planning/benchmark-history.md is stale -- "
            "tools/benchmarks/benchmark_history.jsonl changed without "
            "regenerating it.\nRun 'make benchmark-report' and commit the result."
        )
        return 1

    # newline="\n" for byte-identical output on every platform; see
    # generate_docs_index.py's own note for what goes wrong without it.
    with OUTPUT_PATH.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(content)
    print(f"Wrote {OUTPUT_PATH.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
